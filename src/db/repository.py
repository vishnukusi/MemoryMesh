    def get_graph_overview(self, limit: int = 100) -> list[dict]:
        """Get nodes and edges for visualization."""
        try:
            result = self.graph.ro_query(
                Q.GET_ALL_NODES_AND_EDGES, params={"limit": limit}
            )
            rows = []
            if result.result_set:
                for row in result.result_set:
                    entry = {"node": _node_to_dict(row[0])}
                    if row[0] and hasattr(row[0], "labels"):
                        entry["node_labels"] = list(row[0].labels)
                    if row[1] is not None:
                        entry["relationship"] = row[1]
                    if row[2] is not None:
                        entry["target"] = _node_to_dict(row[2])
                        if hasattr(row[2], "labels"):
                            entry["target_labels"] = list(row[2].labels)
                    rows.append(entry)
            return rows
        except Exception as e:
            logger.warning(f"Graph overview failed: {e}")
            return []
