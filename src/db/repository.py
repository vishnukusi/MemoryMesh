    def update_task_status(
        self,
        task_id: str,
        new_status: str,
        expected_revision: int,
        enforce_lifecycle: bool = True,
    ) -> Optional[dict]:
        """Optimistic concurrency update using revision check and lifecycle validation.
        
        Args:
            task_id: The ID of the task to update.
            new_status: Target status.
            expected_revision: The revision expected by the caller.
            enforce_lifecycle: If True, validates status transition rules and blockers.
            
        Returns:
            Updated task dict, or None if revision mismatch.
            Raises TaskLifecycleError on invalid status or transition.
        """
        task = self.get_task(task_id)
        if not task:
            return None

        if enforce_lifecycle:
            current_status = task.get("status", TaskStatus.PENDING.value)
            blockers = self.get_task_blockers(task_id)
            validate_status_transition(current_status, new_status, blockers)

        now = utc_now_iso()
        result = self.graph.query(Q.UPDATE_TASK_STATUS, params={
            "task_id": task_id,
            "new_status": new_status,
            "expected_revision": expected_revision,
            "updated_at": now,
        })
        nodes = _result_nodes(result)
        if not nodes:
            logger.warning(
                f"Task update failed: revision mismatch for {task_id} "
                f"(expected {expected_revision}, actual {task.get('revision')})"
            )
            return None
        return nodes[0]

