    # ─── Fact ────────────────────────────────────────────────────

    def create_fact(self, fact: FactNode, project_id: str, episode_id: Optional[str] = None) -> dict:
        params = fact.model_dump()
        params["project_id"] = project_id
        if params.get("valid_to") is None:
            params["valid_to"] = ""
        if not params.get("created_at"):
            params["created_at"] = params.get("valid_from") or utc_now_iso()
        if not params.get("updated_at"):
            params["updated_at"] = params.get("created_at") or utc_now_iso()
        result = self.graph.query(Q.CREATE_FACT, params=params)
        # Link to project
        if project_id:
            self.graph.query(Q.LINK_FACT_TO_PROJECT, params={
                "project_id": project_id, "fact_id": fact.id,
            })
        # Link to source episode
        if episode_id:
            self.graph.query(Q.LINK_FACT_TO_EPISODE, params={
                "fact_id": fact.id, "episode_id": episode_id,
            })
        return _result_nodes(result)[0] if _result_nodes(result) else {}

    def supersede_fact(self, old_fact_id: str, new_fact: FactNode,
                       project_id: str, episode_id: Optional[str] = None) -> Optional[dict]:
        """Atomically supersede an existing fact with a new one.
        
        The replacement fact is persisted first. If it succeeds, the old fact
        is marked superseded and the [:SUPERSEDES] relationship is linked atomically.
        If the replacement cannot be created, the old fact remains unchanged.
        """
        old_fact = self.get_fact(old_fact_id)
        if not old_fact:
            logger.warning(f"Cannot supersede non-existent fact: {old_fact_id}")
            return None

        now = utc_now_iso()
        new_fact.project_id = project_id
        # Create the new fact first
        created = self.create_fact(new_fact, project_id, episode_id)
        if not created:
            logger.error(f"Failed to persist replacement fact for {old_fact_id}")
            return None

        # Atomically mark old as superseded and link [:SUPERSEDES]
        self.graph.query(Q.SUPERSEDE_FACT, params={
            "old_id": old_fact_id,
            "new_id": new_fact.id,
            "valid_to": now,
            "updated_at": now,
        })
        return created

