    def __init__(self, tenant_id: str):
        self.tenant_id = tenant_id
        self._graph: Optional[Graph] = None

    @property
    def graph(self) -> Graph:
        if self._graph is None:
            self._graph = get_graph(self.tenant_id)
        return self._graph

    # ─── Project ─────────────────────────────────────────────────

    def create_project(self, project: ProjectNode) -> dict:
        params = project.model_dump()
        if not params.get("status"):
            params["status"] = "active"
        if not params.get("created_at"):
            params["created_at"] = utc_now_iso()
        if not params.get("updated_at"):
            params["updated_at"] = params.get("created_at") or utc_now_iso()
        if params.get("description") is None:
            params["description"] = ""
        result = self.graph.query(Q.CREATE_PROJECT, params=params)
        return _result_nodes(result)[0] if _result_nodes(result) else {}

    def get_project(self, project_id: str) -> Optional[dict]:
        result = self.graph.ro_query(Q.GET_PROJECT, params={"id": project_id})
