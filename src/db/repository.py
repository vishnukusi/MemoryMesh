    # ─── Task ────────────────────────────────────────────────────

    def create_task(self, task: TaskNode, project_id: Optional[str] = None) -> dict:
        params = task.model_dump()
        # Validate priority
        params["priority"] = validate_priority(params.get("priority", "medium"))
        if params.get("owner_id") is None:
            params["owner_id"] = ""
        if params.get("description") is None:
            params["description"] = ""
        if not params.get("created_at"):
            params["created_at"] = params.get("updated_at") or utc_now_iso()
        if not params.get("updated_at"):
            params["updated_at"] = params.get("created_at") or utc_now_iso()
        pid = project_id or task.project_id or ""
        params["project_id"] = pid
        result = self.graph.query(Q.CREATE_TASK, params=params)
        if pid:
            self.graph.query(Q.LINK_TASK_TO_PROJECT, params={
                "project_id": pid, "task_id": task.id,
            })
        return _result_nodes(result)[0] if _result_nodes(result) else {}

    def get_project_dependencies(self, project_id: str) -> list[tuple[str, str]]:
        """Return list of (blocked_task_id, blocker_task_id) for the given project."""
        result = self.graph.ro_query(
            Q.GET_PROJECT_DEPENDENCIES, params={"project_id": project_id}
        )
        if result.result_set:
            return [(str(row[0]), str(row[1])) for row in result.result_set if row[0] and row[1]]
        return []

    def create_blocked_by(self, blocked_id: str, blocker_id: str, project_id: Optional[str] = None) -> None:
        """Create a BLOCKED_BY relationship after verifying no dependency cycle exists."""
        pid = project_id
        if not pid:
            task = self.get_task(blocked_id)
            pid = task.get("project_id", "") if task else ""

        if pid:
            existing_deps = self.get_project_dependencies(pid)
            detect_dependency_cycle(blocked_id, blocker_id, existing_deps)

        self.graph.query(Q.CREATE_BLOCKED_BY, params={
            "blocked_id": blocked_id, "blocker_id": blocker_id,
        })

